import { expect, test, vi } from "vitest"
import { downloadPdfReport } from "./pdf"
import { downloadBlob } from "./download-blob"

vi.mock("./download-blob", () => ({ downloadBlob: vi.fn() }))

test("exports a real multi-page report PDF containing branding, all product rows, units and footer", async () => {
  downloadPdfReport("report.pdf", {
    businessName: "Example Store",
    title: "PRODUCT REPORT",
    dateLine: "November 2026",
    sections: [{ head: ["Product", "Quantity", "Revenue"], body: Array.from({ length: 80 }, (_, i) => ["Rice " + (i + 1), "3 bag", "USD 700.00"]) }],
    footerNote: "Generated by VAE Inventory",
  })
  const [filename, blob] = vi.mocked(downloadBlob).mock.calls[0]
  expect(filename).toBe("report.pdf")
  expect(blob.type).toBe("application/pdf")
  const text = await new Promise<string>((resolve, reject) => {
    const reader = new FileReader()
    reader.onload = () => resolve(String(reader.result))
    reader.onerror = reject
    reader.readAsText(blob)
  })
  expect(text).toMatch(/^%PDF-/)
  expect(text).toContain("Example Store")
  expect(text).toContain("PRODUCT REPORT")
  expect(text).toContain("Rice 80")
  expect(text).toContain("3 bag")
  expect(text).toContain("Generated by VAE Inventory")
  expect((text.match(/\/Type \/Page\b/g) ?? []).length).toBeGreaterThan(1)
})
